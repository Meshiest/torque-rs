//! The plain connect request (no block, no networked plugins) pinned byte for byte. The bytes were produced by the encoder
//! as it was before the connect block existed, so a change that alters what a Torque-only peer sends or reads fails here.

use torque_net::handshake::{ConnectFields, connect_request};
use torque_net::huffman::Table;
use torque_net::profile::HandshakeProfile;

const GOLDEN: &[u8] = &[
    0x20, 0x07, 0x00, 0x00, 0x00, 0x04, 0x03, 0x02, 0x01, 0x08, 0x07, 0x06, 0x05, 0x0c, 0x0b, 0x0a,
    0x09, 0x10, 0x0f, 0x0e, 0x0d, 0x1d, 0x62, 0x13, 0xfd, 0x6a, 0x4a, 0xf4, 0x18, 0x58, 0x09, 0x00,
    0x00, 0x00, 0xe0, 0xff, 0xff, 0xff, 0xff, 0xc5, 0x5a, 0x2d, 0xb2, 0xf9, 0xbf, 0xd8, 0x44, 0x7f,
    0x71, 0xea, 0x99, 0xfe, 0x9c, 0x1f, 0x29, 0x03, 0x00, 0x00, 0x00, 0x03, 0x00, 0x00, 0x40, 0x83,
    0xf6, 0xd8, 0x1e, 0x04, 0x00, 0x00, 0x00, 0x12, 0xb8, 0x25, 0xfa, 0x03, 0xe2, 0xbe, 0x23,
];

#[test]
fn a_plain_connect_request_is_the_bytes_it_always_was() {
    let bytes = connect_request(
        &HandshakeProfile::default(),
        &Table::torque(),
        7,
        [0x0102_0304, 0x0506_0708, 0x090a_0b0c, 0x0d0e_0f10],
        b"GameConnection",
        &ConnectFields::standard(b"secret", vec![b"Name".to_vec(), b"123".to_vec()]),
    );
    assert_eq!(bytes, GOLDEN);
}
