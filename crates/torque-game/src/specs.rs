/// Registers every class of [`CLASSES`] that `vm` does not have yet (by name); returns how many it added.
pub fn install(vm: &mut Vm) -> usize {
    let mut added = 0;
    for spec in CLASSES {
        if vm.objects().classes.find(spec.name.as_bytes()).is_some() {
            continue;
        }
        added += usize::from(install_spec(vm, spec));
    }
    added
}

/// Registers the classes of [`MAP_CLASSES`] that `vm` does not have yet (their parents, `SceneObject` and `NetObject`, must
/// be there), each with the host's own fields and defaults of `extra` that name it; returns how many it added. A second
/// call adds none.
pub fn install_map_classes(vm: &mut Vm, extra: &[ClassExtra]) -> usize {
    let mut added = 0;
    for spec in CLASSES.iter().filter(|c| MAP_CLASSES.contains(&c.name)) {
        if vm.objects().classes.find(spec.name.as_bytes()).is_some() {
            continue;
        }
        let own = extra
            .iter()
            .find(|e| e.class.eq_ignore_ascii_case(spec.name));
        added += usize::from(install_spec_with(vm, spec, own));
    }
    added
}

