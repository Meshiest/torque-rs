//! The console classes of the game layer as TGE 1.4 declares them in their `initPersistFields`: each class's parent and the
//! fields it adds (name, type, element count), in registration order. [`install`] gives them to a `Vm` that has no class of the
//! name yet, so a host's own table (installed first) keeps its classes. The methods are the console methods TGE 1.4 declares on
//! the scene, shape, Player, Item, Camera and vehicle classes and on the connections, with their argument counts (this crate's
//! natives and the network host's replace the stubs). A fresh object reads its type's zero where TGE's constructor would set a
//! value, but for `SceneObject`'s transform and scale (the identity and 1, which its subclasses read), the shape datablocks'
//! numbers (`ShapeBaseData`'s and `PlayerData`'s constructors: a Player's speeds, forces and resistances) and the classes of a
//! mission's world ([`MAP_CLASSES`]), which read the values their TGE constructors set.
//!
//! The fields follow TGE's declarations as in Torque3D's MIT-licensed sources (`T3D/gameBase/gameBase.cpp`,
//! `T3D/shapeBase.cpp`, `T3D/player.cpp` and the others of each class; Copyright (c) 2012 GarageGames, LLC; Copyright (C) 2015
//! Faust Logic, Inc.); `DecalData`'s are TGE 1.4's (`sim/decalManager.cc`, Copyright (C) GarageGames.com, Inc.), which
//! Torque3D replaced. The classes of a mission's world and their defaults follow TGE 1.4's `terrain/terrData.cc`,
//! `terrain/waterBlock.cc`, `interior/interiorInstance.cc`, `game/missionArea.cc` (Copyright (C) GarageGames.com, Inc.) and
//! `game/fx/fxFoliageReplicator.cc` and `game/fx/fxShapeReplicator.cc` (written by Melvyn May; in Torque3D as `T3D/fx/`,
//! Copyright (c) 2012 GarageGames, LLC; `fxFoliageReplicator.cpp` also Copyright (C) 2015 Faust Logic, Inc.). Enumerated fields and types this layer does not model yet are kept as written (`FieldType::Opaque`); two
//! fields of one class that name the same member share its storage (`position` and `rotation`, the `hudImageName` aliases).
//!
//! The engine's own classes after Torque3D's, not TGE's (`SpotLight`, `TimeOfDay`, `ScatterSky`), take their fields and defaults
//! from Torque3D's MIT-licensed `T3D/lightBase.cpp`, `T3D/spotLight.cpp`, `environment/timeOfDay.cpp` and
//! `environment/scatterSky.cpp` (each Copyright (c) 2012 GarageGames, LLC; `lightBase.cpp` also Copyright (C) 2015 Faust Logic,
//! Inc.); a TimeOfDay's `time` starts at its `startTime`.
//!
//! A host whose own table lacks some of these classes on purpose (a class it registers only in some modes) does not call
//! [`install`]: it would make them exist everywhere. One that registers the world classes only while it runs a mission calls
//! [`install_map_classes`] then, with its own fields on them ([`ClassExtra`]).

use ts_vm::classes::{
    ClassExtra, ClassSpec, FieldSpec, MethodSpec, Returns, install_spec, install_spec_with,
};
use ts_vm::fields::{EnumTable, FieldType};
use ts_vm::vm::Vm;

const fn field(name: &'static str, ty: FieldType, count: u16) -> FieldSpec {
    FieldSpec {
        name,
        ty,
        count,
        offset: None,
        validator: None,
    }
}

/// A field that shares its storage with the others of its class at `offset`.
const fn shared(name: &'static str, ty: FieldType, count: u16, offset: u32) -> FieldSpec {
    FieldSpec {
        name,
        ty,
        count,
        offset: Some(offset),
        validator: None,
    }
}

