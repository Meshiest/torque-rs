//! Writes the reference as markdown pages.
//!
//! The pages depend only on the [`Reference`]: entries are sorted without regard to case, and nothing in them comes from the
//! machine or the run.

use std::collections::BTreeMap;
use std::fmt::Write;

use crate::model::{Class, Field, Native, Pref, Reference, Sides};

/// The folder the pages go in, below the guide's `src`.
pub const FOLDER: &str = "reference/script";

/// The pages as `(file name, text)`, in the order the guide lists them.
pub fn pages(reference: &Reference) -> Vec<(&'static str, String)> {
    vec![
        ("index.md", index(reference)),
        ("functions.md", functions(reference)),
        ("methods.md", methods(reference)),
        ("classes.md", classes(reference)),
        ("prefs.md", prefs(reference)),
    ]
}

const GENERATED: &str = "<!-- Generated by `just script-reference`; do not edit. -->";

fn index(reference: &Reference) -> String {
    let functions = reference.natives.iter().filter(|n| !n.method).count();
    let methods = reference.natives.len() - functions;
    let fields: usize = reference.classes.iter().map(|c| c.fields.len()).sum();
    let mut out = String::new();
    let _ = writeln!(out, "{GENERATED}\n");
    out.push_str(
        "# Script reference\n\n\
         Every console function, method, class and pref of an engine built from `DefaultPlugins`, read from the script engines \
         it makes: the server's and the client's. The pages are written by the `torque-script-reference` tool \
         (`just script-reference`) and checked in, so a change to the scripts' surface shows as a change to them; CI fails \
         when they are stale.\n\n",
    );
    let _ = writeln!(
        out,
        "| Page | What it lists | Entries |\n|---|---|---|\n\
         | [Functions](functions.md) | console functions, by namespace | {functions} |\n\
         | [Methods](methods.md) | methods called on an object, by class | {methods} |\n\
         | [Classes](classes.md) | console classes and the fields they add | {} classes, {fields} fields |\n\
         | [Prefs](prefs.md) | `$Pref::` globals with their defaults and ranges | {} |\n",
        reference.classes.len(),
        reference.prefs.len(),
    );
    out.push_str(
        "## Reading an entry\n\n\
         - Each entry says which script engine has it: the **server**'s, the **client**'s or both.\n\
         - The usage text is what the native prints when it is called with the wrong number of arguments, and what \
         `obj.dump()` lists. An entry made with `#[torque::function]` or `#[torque::methods]` also shows the rest of its \
         doc comment (see [Script functions from Rust](../../script-functions.md)).\n\
         - An argument count is the number of arguments a script passes, not counting the function's name or a method's object.\n\
         - A class lists only the fields it adds; it has its parent's too. A default is shown only for a class declared in Rust with `#[derive(EngineClass)]`, where it is the declaration's; the original classes set theirs in code the tables do not hold. A \
         range is what a write is clamped to.\n\
         - Names compare without case in a script, so the pages sort them without case.\n\n",
    );
    if !reference.optional.is_empty() {
        out.push_str(
            "## Opt-in plugins\n\n\
             These plugins are not in `DefaultPlugins`. What each adds is listed with the plugin's id beside it, since a game \
             that does not add the plugin does not have it.\n\n",
        );
        for (id, what) in &reference.optional {
            let _ = writeln!(out, "- `{id}`: {what}");
        }
        out.push_str(
            "\n`LivePerfPlugin` also adds a function and a pref, but its two names are the game's choice, so there is nothing fixed to \
             list.\n",
        );
    }
    out
}

/// A code span that holds `text` whatever backticks it has.
fn code(text: &str) -> String {
    let longest = text
        .split(|c| c != '`')
        .map(str::len)
        .max()
        .unwrap_or_default();
    let fence = "`".repeat(longest + 1);
    let pad = if text.starts_with('`') || text.ends_with('`') {
        " "
    } else {
        ""
    };
    format!("{fence}{pad}{text}{pad}{fence}")
}

/// Text on one line: a table cell or a list item's first line.
fn one_line(text: &str) -> String {
    text.split_whitespace().collect::<Vec<_>>().join(" ")
}

fn tags(sides: &Sides, plugins: &[String]) -> String {
    let mut parts = vec![sides.text().to_string()];
    for plugin in plugins {
        parts.push(format!("needs {}", code(plugin)));
    }
    parts.join("; ")
}

fn lower(text: &str) -> String {
    text.to_ascii_lowercase()
}

/// How a native is called: `name(..)`, `Namespace::name(..)` or `obj.name(..)`, without the arguments.
fn call_name(n: &Native) -> String {
    if n.method {
        format!("obj.{}", n.name)
    } else if n.namespace.is_empty() {
        n.name.clone()
    } else {
        format!("{}::{}", n.namespace, n.name)
    }
}

/// The index of the `)` that closes the `(` at the start of `text`.
fn closing_paren(text: &str) -> Option<usize> {
    let mut depth = 0usize;
    for (i, c) in text.char_indices() {
        match c {
            '(' => depth += 1,
            ')' => {
                depth = depth.checked_sub(1)?;
                if depth == 0 {
                    return Some(i);
                }
            }
            _ => {}
        }
    }
    None
}

/// A signature on one line, without the `;` some usage texts end with.
fn bare(signature: &str) -> String {
    one_line(signature)
        .trim_end_matches(';')
        .trim_end()
        .to_string()
}

/// A native's usage text as its signature and the description after it. The engine's own usage texts take a few forms: the
/// whole signature (`getWords(text, first) - the words`), the arguments alone (`(S32 sequence)`, sometimes followed by a
/// longer description) or just a description.
fn signature(n: &Native) -> (String, String) {
    let usage = n.usage.trim();
    let call = call_name(n);
    // Without a signature of its own, a native that takes nothing is shown with empty parentheses.
    let bare_call = if n.arity.max == Some(0) {
        format!("{call}()")
    } else {
        call.clone()
    };
    if usage.is_empty() {
        return (bare_call, String::new());
    }
    if usage.starts_with('(')
        && let Some(close) = closing_paren(usage)
    {
        let args = one_line(&usage[1..close]);
        let rest = usage[close + 1..].trim_start_matches([';', ' ']);
        let rest = rest.strip_prefix("- ").unwrap_or(rest);
        return (format!("{call}({args})"), rest.trim().to_string());
    }
    let first = usage.lines().next().unwrap_or_default();
    let rest_lines = usage.split_once('\n').map_or("", |(_, rest)| rest);
    if let Some((before, after)) = first.split_once(" - ")
        && before.contains('(')
    {
        let description = [after, rest_lines].join("\n");
        return (bare(before), description.trim().to_string());
    }
    let call_like = first
        .split_once('(')
        .is_some_and(|(head, _)| !head.is_empty() && !head.contains(char::is_whitespace));
    if call_like {
        return (bare(first), rest_lines.trim().to_string());
    }
    (bare_call, usage.to_string())
}

fn native_item(out: &mut String, n: &Native) {
    let (signature, description) = signature(n);
    let mut lines = description.lines().peekable();
    let _ = write!(out, "- {}", code(&signature));
    if let Some(first) = lines.next_if(|l| !l.trim_start().starts_with('@')) {
        let first = first.trim();
        if !first.is_empty() {
            let _ = write!(out, " - {}", escape_text(first));
        }
    }
    out.push('\n');
    while lines.next_if(|l| l.trim().is_empty()).is_some() {}
    let rest: Vec<&str> = lines.collect();
    if !rest.is_empty() {
        out.push_str("\n  ```text\n");
        for line in &rest {
            if line.trim().is_empty() {
                out.push('\n');
            } else {
                let _ = writeln!(out, "  {line}");
            }
        }
        out.push_str("  ```\n\n");
    }
    let mut notes = vec![format!("arguments: {}", n.arity.text())];
    if n.dev {
        notes.push("development command".to_string());
    }
    notes.push(tags(&n.sides, &n.plugins));
    let _ = writeln!(out, "  *{}*", notes.join("; "));
    if !n.docs.is_empty() {
        out.push('\n');
        for line in n.docs.lines() {
            if line.is_empty() {
                out.push('\n');
            } else {
                let _ = writeln!(out, "  {line}");
            }
        }
        out.push('\n');
    }
}

/// Text that is not markup: the characters that would start some are escaped.
fn escape_text(text: &str) -> String {
    let mut out = String::with_capacity(text.len());
    for c in text.chars() {
        if matches!(c, '<' | '>' | '*' | '[' | ']' | '`' | '|' | '\\') {
            out.push('\\');
        }
        out.push(c);
    }
    out
}

/// The natives of one kind grouped by namespace without case, in the order of the namespace's first spelling.
fn grouped(reference: &Reference, method: bool) -> BTreeMap<String, (String, Vec<&Native>)> {
    let mut groups: BTreeMap<String, (String, Vec<&Native>)> = BTreeMap::new();
    for native in reference.natives.iter().filter(|n| n.method == method) {
        groups
            .entry(lower(&native.namespace))
            .or_insert_with(|| (native.namespace.clone(), Vec::new()))
            .1
            .push(native);
    }
    for (_, natives) in groups.values_mut() {
        natives.sort_by_key(|n| (lower(&n.name), n.usage.clone()));
    }
    groups
}

fn natives_page(reference: &Reference, method: bool) -> String {
    let (title, lead, what) = if method {
        (
            "Methods",
            "Methods called on an object (`%obj.name(..)`), by the class whose namespace has them. A method is found up the class's parents, so `SimObject`'s are on every object.",
            "class",
        )
    } else {
        (
            "Functions",
            "Console functions, by namespace. Functions of the global namespace are called as `name(..)`, the others as `Namespace::name(..)`.",
            "namespace",
        )
    };
    let groups = grouped(reference, method);
    let mut out = format!("{GENERATED}\n\n# {title}\n\n{lead}\n\n");
    let total: usize = groups.values().map(|(_, n)| n.len()).sum();
    let noun = match (method, groups.len()) {
        (true, 1) => "class",
        (true, _) => "classes",
        (false, 1) => "namespace",
        (false, _) => "namespaces",
    };
    let _ = writeln!(out, "{total} entries in {} {noun}.\n", groups.len());
    if groups.len() > 1 {
        let _ = writeln!(out, "| {} | Entries |\n|---|---|", capitalize(what));
        for (name, natives) in groups.values() {
            let shown = heading_name(name);
            let _ = writeln!(
                out,
                "| [{}](#{}) | {} |",
                shown,
                anchor(&shown),
                natives.len()
            );
        }
        out.push('\n');
    }
    for (name, natives) in groups.values() {
        let _ = writeln!(out, "## {}\n", heading_name(name));
        for native in natives {
            native_item(&mut out, native);
        }
        out.push('\n');
    }
    trim_end(out)
}

fn heading_name(namespace: &str) -> String {
    if namespace.is_empty() {
        "Global".to_string()
    } else {
        namespace.to_string()
    }
}

/// The id mdBook gives a heading: lower case, spaces as `-`.
fn anchor(heading: &str) -> String {
    heading
        .chars()
        .filter(|c| c.is_alphanumeric() || matches!(c, '_' | '-' | ' '))
        .map(|c| {
            if c == ' ' {
                '-'
            } else {
                c.to_ascii_lowercase()
            }
        })
        .collect()
}

fn capitalize(word: &str) -> String {
    let mut chars = word.chars();
    chars
        .next()
        .map(|c| c.to_uppercase().chain(chars).collect())
        .unwrap_or_default()
}

fn trim_end(mut text: String) -> String {
    while text.ends_with("\n\n") {
        text.pop();
    }
    text
}

fn functions(reference: &Reference) -> String {
    natives_page(reference, false)
}

fn methods(reference: &Reference) -> String {
    natives_page(reference, true)
}

fn field_row(out: &mut String, f: &Field, show_default: bool, show_sides: bool) {
    let name = if f.count > 1 {
        format!("{}[{}]", f.name, f.count)
    } else {
        f.name.clone()
    };
    let default = if f.default.is_empty() {
        String::new()
    } else {
        code(&one_line(&f.default))
    };
    let range = f.range.clone().unwrap_or_default();
    let _ = write!(out, "| {} | {} |", code(&name), escape_cell(&f.ty));
    if show_default {
        let _ = write!(out, " {default} |");
    }
    let _ = write!(out, " {} | {}", range, escape_cell(&one_line(&f.doc)));
    if show_sides {
        let _ = write!(out, " | {}", f.sides.text());
    }
    out.push_str(" |\n");
}

fn escape_cell(text: &str) -> String {
    text.replace('|', "\\|")
}

fn classes(reference: &Reference) -> String {
    let mut sorted: Vec<&Class> = reference.classes.iter().collect();
    sorted.sort_by_key(|c| lower(&c.name));
    let mut out = format!(
        "{GENERATED}\n\n# Classes\n\nConsole classes, with the fields each adds to its parent's. {} classes.\n\n",
        sorted.len()
    );
    let _ = writeln!(out, "| Class | Parent | Fields |\n|---|---|---|");
    for class in &sorted {
        let parent = if class.parent.is_empty() {
            String::new()
        } else {
            format!("[{}](#{})", class.parent, anchor(&class.parent))
        };
        let _ = writeln!(
            out,
            "| [{}](#{}) | {} | {} |",
            class.name,
            anchor(&class.name),
            parent,
            class.fields.len()
        );
    }
    out.push('\n');
    for class in sorted {
        let _ = writeln!(out, "## {}\n", class.name);
        let mut notes = Vec::new();
        if !class.parent.is_empty() {
            notes.push(format!("goes below `{}`", class.parent));
        }
        notes.push(tags(&class.sides, &class.plugins));
        let _ = writeln!(out, "*{}*\n", notes.join("; "));
        if class.fields.is_empty() {
            out.push_str("No fields of its own.\n\n");
            continue;
        }
        let show_sides = class.fields.iter().any(|f| f.sides != class.sides);
        let default = if class.declared { " Default |" } else { "" };
        let rule = if class.declared { "---|" } else { "" };
        let _ = writeln!(
            out,
            "| Field | Type |{default} Range | What it is for |{}\n|---|---|{rule}---|---|{}",
            if show_sides { " Side |" } else { "" },
            if show_sides { "---|" } else { "" }
        );
        for field in &class.fields {
            field_row(&mut out, field, class.declared, show_sides);
        }
        out.push('\n');
    }
    trim_end(out)
}

fn pref_row(out: &mut String, p: &Pref) {
    let _ = writeln!(
        out,
        "| {} | {} | {} | {} | {} | {} |",
        code(&p.name),
        p.ty,
        code(&one_line(&p.default)),
        p.range.clone().unwrap_or_default(),
        escape_cell(&one_line(&p.doc)),
        tags(&p.sides, &p.plugins),
    );
}

fn prefs(reference: &Reference) -> String {
    let mut sorted: Vec<&Pref> = reference.prefs.iter().collect();
    sorted.sort_by_key(|p| lower(&p.name));
    let mut out = format!(
        "{GENERATED}\n\n# Prefs\n\nPrefs are `$Pref::` globals a plugin gives a default before any script runs (`#[derive(Prefs)]`). \
         A read in Rust clamps the value to the range; the global keeps what a script wrote. {} prefs.\n\n",
        sorted.len()
    );
    if sorted.is_empty() {
        out.push_str("No plugin of `DefaultPlugins` declares a pref yet.\n");
        return out;
    }
    out.push_str(
        "| Pref | Type | Default | Range | What it is for | Where |\n|---|---|---|---|---|---|\n",
    );
    for pref in sorted {
        pref_row(&mut out, pref);
    }
    out
}
