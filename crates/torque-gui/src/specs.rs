//! The console classes this crate implements, as TGE 1.4 declares them: each class's parent, its own fields (name, type,
//! element count) and what a fresh object reads where TGE's constructor sets it. [`install`] gives them to a `Vm` that has no
//! class of the name yet, so a host's own table (installed first) keeps its classes. The methods are this crate's natives
//! ([`crate::register`]).

use torque_ts_vm::classes::{ClassSpec, FieldSpec, install_spec};
use torque_ts_vm::fields::{EnumTable, FieldType};
use torque_ts_vm::vm::Vm;

const fn field(name: &'static str, ty: FieldType, count: u16) -> FieldSpec {
    FieldSpec {
        name,
        ty,
        count,
        offset: None,
        validator: None,
    }
}

